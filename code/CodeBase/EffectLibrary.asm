		..extendbottom
		DEY #2							; read previous entry (data)
		..extendtop
		LDA #$0001 : JMP .Draw

	.End
		STZ !HDMA_Buffer1+0,x					;\ finish table
		LDA !HDMA_WorkingOutput : STA !HDMA_Buffer1_Output,x	;/
		%HDMA_SyncMPU()
		PLD							; restore DP
		PLB
		PLP
		RTL							; return

