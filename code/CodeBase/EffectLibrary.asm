; input:
;	$3100 = scroll offset (16-bit), uses same directions as layer, meaning that + will move the table up and - will move it down
;	$3102 = stretch value (16-bit), added to each scanline count
;	!HDMA_Input = 24-bit pointer to HDMA table
;	format, for each chunk, is as follows:
;	- scanline count (16-bit)
;	- value (8-bit)
;	table ends on a scanline count of 0x00
