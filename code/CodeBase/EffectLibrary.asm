
;==============================
;
; UNDERSTANDING HDMA MODULES
;
;==============================

; HDMA modules are split into 4 main components
; the first component is the HDMA module itself
; a module contains a 5 byte header followed by an arbitry amount of data
; the first 2 bytes of the header are written to $43x0 and $43x1
; the next 3 bytes are a 24-bit pointer to the next component: the module engine

; a module engine is responsible for interpreting the arbitry data in the module and transcribing it to a proper HDMA table in SNES WRAM
; the module engine is a routine called by the SNES
; it can be further split into the last 2 primary components: the logic engine and the transcription engine

; the logic engine is run by SA-1 and takes over the task of interpreting input data
; the transcription engine is run by SNES from inside its WRAM to let SA-1 operate at full speed
; it is responsible for taking data generated by the logic engine and outputting it into a proper HDMA table

; most module engines run in MPU mode: SA-1 interprets data and SNES outputs it
; however, a module engine can be written to be run by solo SNES, which is useful in case the logic is very simple
; in MPU mode, the following protocol is used:
;	- 2 buffers on dp are used to send data from SA-1 to SNES, minimizing write/read time
;	- !HDMA_ProgramState can be in 2 main states: SA-1 writing to buffer 1 or buffer 2
;	- the highest bit in the lo byte is set when SNES is waiting to read a new buffer, which is a requirement for SA-1 to update program state
;	- this method strategically allocates wait time and leaves no opening for the CPUs to desync











