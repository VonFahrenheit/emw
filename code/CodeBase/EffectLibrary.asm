		STA !HDMA_Buffer1+0,x					;\
		LDA $0001,y : STA !HDMA_Buffer1+1,x			; | generate chunk
		LDA !HDMA_WorkingOutput : STA !HDMA_Buffer1_Output,x	;/
		INC #2 : STA !HDMA_WorkingOutput			; output+2
		BRA .Loop						; loop






