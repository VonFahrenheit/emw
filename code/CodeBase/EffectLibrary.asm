		LDA $00							;\
		EOR #$FFFF : INC A					; | initial working position
		STA !HDMA_WorkingY					;/ (how many scanlines have to be skipped due to top of effect being off-screen)
		BMI ..loop
		CMP !HDMA_MaxY : BCS ..extendtop			; check if chunk is scrolled below screen
		..loop
		LDA $0000,y						;\ clause for if table is scrolled so far that only the last chunk is visible
		AND #$00FF : BEQ ..extendbottom				;/
		CLC : ADC $02						; add stretch value
		ADC !HDMA_WorkingY					;\ update working Y pos
		STA !HDMA_WorkingY					;/
		BEQ ..keepscanning					;\
		BMI ..keepscanning					; | see if we have reached an on-screen coord
		JMP .Draw						;/
		..keepscanning						;\ otherwise, input index +2 and loop
