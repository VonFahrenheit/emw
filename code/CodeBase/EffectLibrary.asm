		INY #2							; read index +2
		%HDMA_SyncMPU()
		LDA !HDMA_WorkingY					;\
		CMP !HDMA_MaxY : BCS .End				; |
		LDA $0000,y						; |
		AND #$00FF : BEQ .End					; | check for end of screen and update working Y
		CLC : ADC !HDMA_WorkingY				; |
		ADC $02							; |
		STA !HDMA_WorkingY					;/
		LDA $0000,y						;\
		AND #$00FF						; | get scanline count + stretch value
