;==============================
; when a code pointer is called, SNES is in the following state:
; DP	3000
; B	generic (not K)
; $00	24-bit pointer to module (data starts at [$00],5)
; A	16-bit
; index	8-bit
; X	channel index
; Y	3
; any modification to the $00 pointer will be taken into account by the transcription engine
; they also require X = channel index to be intact

; in MPU mode, modules use DP $3100
; the first 64 bytes ($00-$3F) can be used by both CPUs
; see Defines.asm for memory map






; handles data that has 1 scanline byte and 1 data byte
