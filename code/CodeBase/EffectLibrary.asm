	DirectControl:
	.BG1
	db $03,$210D		; mode 3 -> 210D
	dl ..code		; nested engine
	..code
		LDA !HDMA2location+1,x : STA $00+1
		LDA !HDMA2counter,x
		AND #$0001 : BEQ +
		LDA !HDMA2size,x
	+	CLC : ADC !HDMA2location,x
		STA $00

		LDY #$01
		LDA $1A : STA [$00],y
		LDY #$03
		LDA $1C
		CLC : ADC $7888
		STA [$00],y

		SEP #$20
		INC !HDMA2counter,x
		LDY #$05
		LDA #$00
		STA [$00]
		STA [$00],y

		REP #$20
		LDA $00 : STA !HDMA2source,x
		RTL



