;
; SA-1 LOGIC ENGINES
;
;==============================
; matching SNES transcription engines are found in Engine/MPU.asm

; these codes run in MPU format
; SA-1 handles calculations, while SNES continuously copies SA-1 output into its WRAM table
; this code is called from the camera routine (!HDMAptr), meaning that $3100-$313F is in use by SA-1's GM14 thread
; however, during that phase of GM14, SA-1 only uses the scratch area ($00-$0F) and frame counters ($13-$14)
; this means that $3110-$3112 and $3115-$313F are free to use in this code


; i need a convenient way of setting a channel's output table (along with double-buffer offset)
; possibly just use the unused space in SNES page $01?



; proper procedure for a logic engine is:
;		PHP
;		PHB
;		PHD
;		JSR LogicEngineStart


	LogicEngineStart:
		REP #$30						; all regs 16-bit
		LDA #$3100 : TCD					; DP optimization
		LDA $3000						;\
		CLC : ADC #$0005					; |
		STA !HDMA_Input						; |
		TAY							; | get module data
		SEP #$20						; |
		LDA $3000+2 : STA !HDMA_Input+2				; |
		PHA : PLB						;/
		REP #$30						; all regs 16-bit
		LDX #$0000						; start at buffer 1
		LDA !HDMA_Output : STA !HDMA_WorkingOutput		; copy output to DP
		RTS


; use this macro to sync program state with SNES side whenever SA-1 should start writing a new buffer

	macro HDMA_SyncMPU()
	-	BIT !HDMA_ProgramState-1 : BPL -			; wait for SNES to spin
		TXA							;\ update buffer index
		EOR #$0008 : TAX					;/
		BNE ?state2						;\
		?state1:						; |
		STZ !HDMA_ProgramState : BRA ?sync			; | update program state
		?state2:						; |
		LDA #$8000 : STA !HDMA_ProgramState			; |
		?sync:							;/
	endmacro












; input:
;	!HDMA_Input = 24-bit pointer to HDMA table
;	format, for each chunk, is as follows:
;	- scanline count (16-bit)
;	- fraction (3 16-bit numbers: loop value (512*divisor/factor), factor, divisor)
;	table ends on a scanline count of 0x0000
	Logic_BG2Parallax:
		PHP
		PHB
		PHD
		JSR LogicEngineStart

	.PreCalc
		LDA $20							;\
		EOR #$FFFF : INC A					; | initial working position
		STA !HDMA_WorkingY					;/ (how many scanlines have to be skipped due to top of BG2 being off-screen)
		BMI ..loop
		CMP !HDMA_MaxY : BCS ..extendtop
		..loop
		LDA $0000,y : BEQ ..extendbottom			; clause for if BG2 is scrolled so far that only the last chunk is visible
		CLC : ADC !HDMA_WorkingY				;\ update working Y pos
		STA !HDMA_WorkingY					;/
		BEQ ..keepscanning					;\
		BMI ..keepscanning					; | see if we have reached an on-screen coord
		JMP .Draw						;/
		..keepscanning						;\
		TYA							; |
		CLC : ADC #$0008					; | otherwise, input index +8 and loop
		TAY							; |
		BRA ..loop						;/
		..extendbottom
		TYA							;\
		SEC : SBC #$0008					; | read previous entry (scroll factors only)
		TAY							;/
		..extendtop
		LDA #$0001 : JMP .Draw

	.End
		STZ !HDMA_Buffer1_Lines,x				;\ finish table
		LDA !HDMA_WorkingOutput : STA !HDMA_Buffer1_Output,x	;/
		%HDMA_SyncMPU()
		PLD							; restore DP
		PLB
		PLP
		RTL							; return

	.Loop
		TYA							;\
		CLC : ADC #$0008					; | next source table entry
		TAY							;/
		%HDMA_SyncMPU()
		LDA !HDMA_WorkingY					;\
		CMP !HDMA_MaxY : BCS .End				; | check for end of screen and update working Y
		ADC $0000,y						; |
		STA !HDMA_WorkingY					;/
		LDA $0000,y : BEQ .End					; get scanline count

	; A = scanline count
	.Draw
		STZ $2250						; prepare multiplication
		STA !HDMA_Buffer1_Lines,x				; scanline count
		LDA !HDMA_WorkingOutput : STA !HDMA_Buffer1_Output,x	; output address
		CLC : ADC #$0003					;\ update output
		STA !HDMA_WorkingOutput					;/
		LDA $1E							;\	
	-	CMP $0002,y : BCC +					; |
		SBC $0002,y : BRA -					; | queue multiplication
	+	STA $2251						; |
		LDA $0004,y : STA $2253					;/
		STX !HDMA_WorkingIndex					;\ wait
		LDX #$0001						;/
		LDA $2306						; get product
		STX $2250						;\
		STA $2251						; | queue division
		LDA $0006,y : STA $2253					;/
		LDX !HDMA_WorkingIndex					;\ reload X index and waste some cycles
		NOP							;/
		LDA $2306 : STA !HDMA_Buffer1_Data,x			; write scroll value

		BRA .Loop						; loop





; input:
;	!HDMA_Input = 24-bit pointer to HDMA table
;	format is 16-bit byte count followed by a 16-bit factor (8.8 format) for each chunk
;	table length should match the header word
;
; output:
;	$0C	number of bytes written to skeleton table
;	!BigRAM	skeleton table, 4 bytes for each rendered chunk
;		first word is scanline count of chunk
;		second word is chunk's ID, which is its index to the factor table (0xFFFF for dummy chunks)
;
; projection variables:
;	c (level position of camera center, $1C + 0x0070)
;	wl (level position of water level)
;
; scratch:
;	$00		base YZ distance (wl-c)
;	$02		dummy coord (used for filling in empty chunks)
;	$04		cut flag (n-trigger, if set, the current chunk's YZ coordinate is treated as 0 for the purposes of calculating its scanline count)
;	$06		tempX
;	$08		tempY
;	$0A		table length
;	$0C		pointer to !BigRAM, incremented to output scanline counts
;	$0E		!HDMA_Input+table length (pointer to second table)
;	!HDMA_Misc	holds value read from ($0E)

	Logic_BG3Projection:
		PHP
		PHB
		PHD
		JSR LogicEngineStart

	.PreCalc
		STZ !HDMA_WorkingY					; start from scanline 0
		STZ $04							; cut flag

		LDA (!HDMA_Input) : STA $02				; dummy coord
		LDY #$0002 : LDA (!HDMA_Input),y : STA $0A		; table length
		LDY #$0004 : LDA (!HDMA_Input),y : STA $0E		; pointer to coordinate table
		LDA.w #!BigRAM : STA $0C				; pointer to where scanline table will be dumped
		LDA !HDMA_Input						;\
		CLC : ADC #$0006					; | repoint input to low projection factor table
		STA !HDMA_Input						;/
		LDY #$0000						; read table from the front

		STZ $2250						; set ALU to multiplication
		LDA $1C							;\
		CLC : ADC #$0078					; | check if camera is above or below projection
		CMP !Level+2 : BCC .LowProjection			; | (this has an extra 8px of leeway to make the transition work better with the SNES limitations)
		JMP .HighProjection					;/

	.LowProjection
		LDA !Level+2						;\
		SEC : SBC $1C						; |
		SEC : SBC #$0070					; | $00 = base YZ distance (wl-c)
		CMP #$FFFD						; |
		BCC $03 : LDA #$FFFE					; > minimum negative YZ distance is -2
		STA $00							;/

		LDA (!HDMA_Input),y : STA $2251				;\ f*yz
		LDA $00 : STA $2253					;/
		NOP
		LDA #$0070
		CLC : ADC $2307
		BEQ ..loop

		..fillerchunk1
		STA !HDMA_WorkingY
		STA ($0C)						;\ output skeleton chunk size
		INC $0C : INC $0C					;/
		CMP #$0080 : BCC ..fillerchunk2
		LSR A : STA !HDMA_Buffer1_Lines,x
		BCC $01 : INC A
		PHA
		LDA $02 : STA !HDMA_Buffer1_Data+2,x
		LDA !HDMA_WorkingOutput : STA !HDMA_Buffer1_Output,x
		CLC : ADC #$0005
		STA !HDMA_WorkingOutput
		%HDMA_SyncMPU()
		PLA

		..fillerchunk2
		STA !HDMA_Buffer1_Lines,x
		LDA $02 : STA !HDMA_Buffer1_Data+2,x
		LDA !HDMA_WorkingOutput : STA !HDMA_Buffer1_Output,x
		CLC : ADC #$0005
		STA !HDMA_WorkingOutput
		%HDMA_SyncMPU()

		LDA #$FFFF : STA ($0C)					;\ output skeleton chunk ID
		INC $0C : INC $0C					;/

		; $2251 = f
		; $2253 = YZ
		..loop
		LDA #$0070						;\
		CLC : ADC $2307						; | temp YZ
		STA $08							;/

		LDA $22 : STA $2253					;\
		LDA ($0E) : STA !HDMA_Misc				; | temp X + read display coord
		INC $0E : INC $0E
		LDA $2307 : STA $06					;/

		INY #2							;\
		CPY $0A : BCC ..calcchunk				; | if this is the last chunk, use a scanline count of 8
		LDA #$0008 : BRA ..sendchunk				;/

		..calcchunk
		LDA (!HDMA_Input),y : STA $2251				;\
		LDA $00 : STA $2253					; |
		NOP							; |
		LDA #$0070						; | scanline count = f+1*YZ - f*YZ
		CLC : ADC $2307						; |
		BIT $04 : BMI ..sendchunk				; |
		SEC : SBC $08						;/

		..sendchunk
		CMP #$0000 : BEQ ..next					; 0 = skip this chunk
		STA !HDMA_Buffer1_Lines,x				; send scanline count
		STA ($0C)						;\ output skeleton chunk size
		INC $0C : INC $0C					;/
		CLC : ADC !HDMA_WorkingY				;\ update working
		STA !HDMA_WorkingY					;/
		TYA							;\
		DEC #2 : STA ($0C)					; | output skeleton chunk ID
		INC $0C : INC $0C					;/
		LDA $06 : STA !HDMA_Buffer1_Data,x			; send X scroll
		LDA !HDMA_Misc						;\
		SEC : SBC $08						; | send Y scroll
		STA !HDMA_Buffer1_Data+2,x				;/
		LDA !HDMA_WorkingOutput : STA !HDMA_Buffer1_Output,x	; send output
		CLC : ADC #$0005					;\ update output
		STA !HDMA_WorkingOutput					;/

		%HDMA_SyncMPU()

		STZ $04

		..next
		CPY $0A : BCS ..end
		JMP ..loop

		..end
		JMP .End


	.HighProjection
		LDA $22 : STA $2251
		LDA !Level+2
		SEC : SBC $1C
		STA $00
		LDA $0A
		DEC #2 : STA $06					; $06 = last index to read ($0A = index to end at)

		; search table for first chunk to have a factor greater than 1.0
		; place that chunk on wl
		; adjust so each chunk is 1 scanline tall, with y-position based on the 1.0 chunk
		; chunks before the 1.0 one are placed above
		; chunks after are placed below
		; coords are used as usual
		; last chunk is 8px tall

		..search
		LDA (!HDMA_Input),y
		CMP #$0100 : BCS ..found
		INY #2
		CPY $0A : BCC ..search
		; if this error somehow occurs, just let it flow
		..found

		TYA
		LSR A
		SEC : SBC $00
		BNE $03 : JMP ..renderfromtop
		EOR #$FFFF : INC A
		BMI ..cut
		CMP #$00E0
		BCC $03 : LDA #$00E0
		BRA ..fillerchunk1

		; A = number of scanlines above first water chunk
		; if A is positive, we need filler chunks
		; if A is 0, the water chunks start at the top
		; if A is negative, -A number of chunks have to be skipped
		; (if this cuts into the last chunk, it might be cut

		..cut
		EOR #$FFFF : INC A					;\ $04 = number of scanlines to cut
		STA $04							;/
		LDA $0A							;\
		LSR A							; | total height of projection = table length/2 +7 (last chunk is 8px instead of 1px)
		ADC #$0007						;/
		SEC : SBC $04						;\
		BCC +							; | if the whole projection is cut, just end the table
		BEQ +							;/
		; A = number of scanlines to show
		CMP #$0008 : BCS ..multi
		..lastonly
		STA !HDMA_Buffer1_Lines,x
		STA ($0C)
		INC $0C : INC $0C
		LDY $06
		LDA (!HDMA_Input),y : STA $2253
		TYA : STA ($0C)
		INC $0C : INC $0C
		LDA ($0E),y
		SEC : SBC !HDMA_Buffer1_Lines,x
		STA !HDMA_Buffer1_Data+2,x
		LDA $2307 : STA !HDMA_Buffer1_Data+0,x
		LDA !HDMA_WorkingOutput : STA !HDMA_Buffer1_Output,x
		CLC : ADC #$0005
		STA !HDMA_WorkingOutput
		%HDMA_SyncMPU()
	+	JMP .End
		..multi
		LDA $04
		ASL A : TAY
		BRA ..loop

		..fillerchunk1
		STA !HDMA_WorkingY
		STA ($0C)
		INC $0C : INC $0C
		CMP #$0080 : BCC ..fillerchunk2
		LSR A : STA !HDMA_Buffer1_Lines,x
		BCC $01 : INC A
		PHA
		LDA $02 : STA !HDMA_Buffer1_Data+2,x
		LDA !HDMA_WorkingOutput : STA !HDMA_Buffer1_Output,x
		CLC : ADC #$0005
		STA !HDMA_WorkingOutput
		%HDMA_SyncMPU()
		PLA
		..fillerchunk2
		STA !HDMA_Buffer1_Lines,x
		LDA $02 : STA !HDMA_Buffer1_Data+2,x
		LDA !HDMA_WorkingOutput : STA !HDMA_Buffer1_Output,x
		CLC : ADC #$0005
		STA !HDMA_WorkingOutput
		%HDMA_SyncMPU()
		LDA #$FFFF : STA ($0C)
		INC $0C : INC $0C

		..renderfromtop
		LDY #$0000

		..loop
		LDA (!HDMA_Input),y : STA $2253
		LDA #$0001
		CPY $06
		BNE $03 : LDA #$0008
		STA !HDMA_Buffer1_Lines,x
		STA ($0C)
		INC $0C : INC $0C
		CLC : ADC !HDMA_WorkingY
		STA !HDMA_WorkingY
		TYA : STA ($0C)
		INC $0C : INC $0C
		LDA $2307 : STA !HDMA_Buffer1_Data+0,x
		LDA ($0E),y
		SEC : SBC !HDMA_WorkingY
		STA !HDMA_Buffer1_Data+2,x
		LDA !HDMA_WorkingOutput : STA !HDMA_Buffer1_Output,x
		CLC : ADC #$0005
		STA !HDMA_WorkingOutput
		%HDMA_SyncMPU()
		INY #2
		CPY $0A : BCC ..loop




